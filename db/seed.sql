-- ---------------------------------------------------------------------
-- 2. 使用记录表种子数据（至少 5 行，关联上面 5 个工具）
--    先清空再插入，保证重复执行结果一致（幂等）。
--    TRUNCATE ... RESTART IDENTITY：清空数据并把自增主键归零，
--    这样每次执行后 id 都从 1 重新排，结果可复现。
-- ---------------------------------------------------------------------
TRUNCATE tool_usage RESTART IDENTITY;

INSERT INTO tool_usage (tool_id, action, used_at, detail)
SELECT t.id, v.action, v.used_at, v.detail
FROM (
    VALUES
        ('timer',     'start',    '2026-10-02 09:15:00+08'::timestamptz, '25 分钟番茄钟'),
        ('timer',     'start',    '2026-10-02 10:30:00+08'::timestamptz, '5 分钟短休息'),
