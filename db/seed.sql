        ('converter', 'convert',  '2026-10-02 14:05:00+08'::timestamptz, '0 摄氏度 -> 32 华氏度'),
        ('password',  'copy',     '2026-10-02 15:40:00+08'::timestamptz, '生成 32 位密码并复制')
) AS v(slug, action, used_at, detail)
JOIN tools t ON t.slug = v.slug;

